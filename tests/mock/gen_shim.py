"""Generates the mock shim's trampolines from the mock driver's exports.

The WSL libcuda.so.1 is a loader: every export is a tiny jump through a
pointer that its constructor fills with dlsym() on the real driver. This script
emits the same structure for the mock driver, one `jmp *slot(%rip)` per export.

usage: gen_shim.py <mock driver .so> <output .s>
"""

import subprocess
import sys


def exported_functions(lib: str) -> list[str]:
    out = subprocess.run(["nm", "-D", "--defined-only", lib], check=True,
                         capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] == "T" and parts[2].startswith(("cu", "mock_")):
            names.add(parts[2])
    return sorted(names)


def render(names: list[str]) -> str:
    lines = ["# Generated by gen_shim.py. Do not edit.", ".text"]
    for i, name in enumerate(names):
        lines += [f".globl {name}", f".type {name}, @function", f"{name}:",
                  f"    jmp *mock_shim_slots+{8 * i}(%rip)", f".size {name}, .-{name}"]

    lines += [".bss", ".align 8", ".globl mock_shim_slots", ".hidden mock_shim_slots",
              "mock_shim_slots:", f"    .zero {8 * len(names)}"]

    lines += [".section .rodata"]
    lines += [f".Lname{i}: .asciz \"{name}\"" for i, name in enumerate(names)]

    lines += [".section .data.rel.ro", ".align 8", ".globl mock_shim_names",
              ".hidden mock_shim_names", "mock_shim_names:"]
    lines += [f"    .quad .Lname{i}" for i in range(len(names))]

    lines += [".section .rodata", ".align 4", ".globl mock_shim_count", ".hidden mock_shim_count",
              "mock_shim_count:", f"    .long {len(names)}",
              '.section .note.GNU-stack,"",@progbits', ""]
    return "\n".join(lines)


def main() -> int:
    lib, out = sys.argv[1], sys.argv[2]
    names = exported_functions(lib)
    if not names:
        print(f"gen_shim.py: no exports found in {lib}", file=sys.stderr)
        return 1
    with open(out, "w") as f:
        f.write(render(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
